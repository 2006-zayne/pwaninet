    def test_docx_interleaved_sequence_preserved(self):
        elements = [
            ExtractedElement(
                element_type=ElementType.HEADING,
                text="Relational Algebra",
                location=LocationMetadata(block_index=0)
            ),
            ExtractedElement(
                element_type=ElementType.PARAGRAPH,
                text="Relational algebra consists of a collection of operators taking relations as input.",
                location=LocationMetadata(block_index=1)
            ),
            ExtractedElement(
                element_type=ElementType.TABLE,
                text="Operator | Symbol | Description\nSelect | sigma | Filters tuples\nProject | pi | Filters columns",
                location=LocationMetadata(block_index=2),
                metadata={"row_count": 3}
            ),
            ExtractedElement(
                element_type=ElementType.PARAGRAPH,
                text="Additional join operators include theta join and natural join.",
                location=LocationMetadata(block_index=3)
            ),
        ]

        doc = ExtractedDocument(
            source_filename="relational_algebra.docx",
            format="docx",
            elements=elements
        )

        chunks = chunk_document(doc)
        # Heading -> Paragraph, Table, Paragraph sequence
        self.assertEqual(len(chunks), 3)

        # Chunk 0: Paragraph under heading
        self.assertEqual(chunks[0].chunk_type, "paragraph")
        self.assertEqual(chunks[0].section_heading, "Relational Algebra")

        # Chunk 1: Table
        self.assertEqual(chunks[1].chunk_type, "table")
        self.assertIn("Operator | Symbol", chunks[1].content)
        self.assertEqual(chunks[1].metadata.get("row_count"), 3)

        # Chunk 2: Trailing Paragraph
        self.assertEqual(chunks[2].chunk_type, "paragraph")
        self.assertIn("Additional join operators", chunks[2].content)

    def test_large_table_row_boundary_splitting(self):
        # Create a table with 30 rows that exceeds the max token threshold
        header = "ID | Student Name | Course | Grade"
        rows = [f"{i} | Student_{i} | CSC_{100+i} | Pass" for i in range(1, 40)]
        table_text = header + "\n" + "\n".join(rows)

        element = ExtractedElement(
            element_type=ElementType.TABLE,
            text=table_text,
            location=LocationMetadata(page_number=3),
            metadata={"row_count": 40}
        )

        doc = ExtractedDocument(
            source_filename="grades.pdf",
            format="pdf",
            elements=[element]
        )

        config = ChunkingConfig(target_max_tokens=200, max_hard_tokens=250)
        chunks = chunk_document(doc, config=config)

        self.assertGreater(len(chunks), 1)
        for c in chunks:
            self.assertEqual(c.chunk_type, "table")
            self.assertEqual(c.page_number, 3)
            # Table header should be preserved across split pieces
            self.assertTrue(c.content.startswith("ID | Student Name"))
            self.assertTrue(c.metadata.get("is_split_table"))

