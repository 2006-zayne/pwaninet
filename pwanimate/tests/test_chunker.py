    def test_code_block_intact(self):
        code_snippet = (
            "def binary_search(arr, target):\n"
            "    low, high = 0, len(arr) - 1\n"
            "    while low <= high:\n"
            "        mid = (low + high) // 2\n"
            "        if arr[mid] == target:\n"
            "            return mid\n"
            "        elif arr[mid] < target:\n"
            "            low = mid + 1\n"
            "        else:\n"
            "            high = mid - 1\n"
            "    return -1"
        )
        element = ExtractedElement(
            element_type=ElementType.CODE,
            text=code_snippet,
            location=LocationMetadata(page_number=4),
            metadata={"source_extension": "py"}
        )

        doc = ExtractedDocument(
            source_filename="search.py",
            format="py",
            elements=[element]
        )

        chunks = chunk_document(doc)
        self.assertEqual(len(chunks), 1)
        self.assertEqual(chunks[0].chunk_type, "code")
        self.assertIn("def binary_search", chunks[0].content)
        self.assertEqual(chunks[0].metadata.get("language"), "py")

