    def test_persistence_helper_creates_document_chunks(self):
        elements = [
            ExtractedElement(
                element_type=ElementType.PARAGRAPH,
                text="Computer network protocols operate across hierarchical layers.",
                location=LocationMetadata(page_number=1, section_heading="Network Models")
            )
        ]
        doc = ExtractedDocument(source_filename="networks.pdf", format="pdf", elements=elements)
        chunks_data = chunk_document(doc)

        created_chunks = create_document_chunks_from_data(
            document_version=self.version,
            chunks=chunks_data
        )

        self.assertEqual(len(created_chunks), 1)
        db_chunk = DocumentChunk.objects.get(id=created_chunks[0].id)
        self.assertEqual(db_chunk.document, self.document)
        self.assertEqual(db_chunk.document_version, self.version)
        self.assertEqual(db_chunk.chunk_index, 0)
        self.assertFalse(db_chunk.is_active)  # Inactive by default until Phase 2E
        self.assertIn("Computer network protocols", db_chunk.content)
        self.assertIsNotNone(db_chunk.content_hash)
